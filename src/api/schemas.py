"""Request and response models of the core API (/query, /feedback, /ingest, /health, /sidebar-state,
provider and config).
"""
from typing import Literal

from pydantic import BaseModel

from src.api.access import Role


class QueryRequest(BaseModel):
    """Payload for submitting a question to the RAG pipeline."""
    question: str
    session_id: str | None = None
    # "player": the backend restricts the search to player_visible sources itself (metadata_filters can only narrow)
    role: Role = "game_master"
    metadata_filters: dict | None = None
    top_k: int | None = None
    top_k_rerank: int | None = None
    max_per_source: int | None = None
    hybrid_search: bool | None = None


class SourceReference(BaseModel):
    """Metadata about a retrieved chunk used to generate the final answer."""
    file: str
    source_path: str = ""
    document_type: str
    heading: str | None = None
    chunk_preview: str
    score: float


class QueryResponse(BaseModel):
    """The final synchronized answer generated by the LLM, including source references."""
    answer: str
    sources: list[SourceReference]
    session_id: str
    retrieval_scores: list[float]
    model_used: str
    latency_ms: float
    search_query: str = ""  # question used for retrieval — differs from the input when a follow-up was condensed
    timings: dict = {}  # condense/retrieval/total ms, retrieval stages, chunk count, prompt size


class FeedbackRequest(BaseModel):
    """Thumbs up/down on one chat answer. A changed or withdrawn rating is a new entry with the same
    message_id — the last entry per message_id counts."""
    message_id: str
    rating: Literal["up", "down"] | None  # None = rating withdrawn
    role: Role = "game_master"
    question: str = ""
    answer: str = ""
    sources: list[str] = []  # file names shown under the answer
    model: str = ""
    search_query: str = ""
    session_id: str | None = None
    timings: dict = {}


class IngestJobResponse(BaseModel):
    """Acknowledges the scheduling of an asynchronous ingestion background job."""
    job_id: str
    status: str


class IngestStatusResponse(BaseModel):
    """Progress report and current state of a running or completed ingestion job."""
    job_id: str
    status: str
    phase: str = "starting"
    documents_processed: int = 0
    documents_total: int = 0
    documents_skipped: int = 0
    chunks_created: int = 0
    chunks_updated: int = 0
    chunks_deleted: int = 0
    errors: list[str] = []
    duration_seconds: float = 0.0


class HealthResponse(BaseModel):
    """Service health state, including ChromaDB and LLM provider connectivity."""
    status: str
    chromadb: bool
    llm: bool
    sources_configured: bool = True


class StatsResponse(BaseModel):
    """General statistics about the semantic cache."""
    chunk_count: int


class ProviderInfo(BaseModel):
    """Identifies the current active LLM provider and target model."""
    provider: str
    model: str


class GeminiKeyStatus(BaseModel):
    """Detailed status indicating whether a Gemini key is loaded, and from where (env vs runtime)."""
    has_key: bool
    source: str = "none"


class SidebarState(BaseModel):
    """Aggregated state used by the UI's sidebar to reduce API roundtrips."""
    health: HealthResponse
    provider: ProviderInfo
    gemini_status: GeminiKeyStatus
    available_categories: list[str]
    player_source_ids: list[str] = []  # sources searchable in the chat's player mode
    llm_timeout: float = 300  # seconds, active provider — the chat derives its read timeout from it


class SwitchProviderRequest(BaseModel):
    """Payload for changing the active LLM provider at runtime."""
    provider: Literal["ollama", "gemini"]  # anything else → 422


class ConfigUpdateRequest(BaseModel):
    """Partial settings update from the Settings UI. Unknown keys are dropped
    server-side by the ConfigManager allow-list."""
    retrieval: dict | None = None
    llm: dict | None = None
    conversation: dict | None = None
    chunking: dict | None = None
